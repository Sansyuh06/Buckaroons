# Need this import at module level for the slug generation
import re

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Video Factory Pipeline")
    parser.add_argument("--run-now", action="store_true",
                        help="Run one video immediately")
    parser.add_argument("--schedule", action="store_true",
                        help="Start the scheduler")
    parser.add_argument("--seed", type=int, default=None,
                        help="Random seed for reproducibility")
    parser.add_argument("--skip-mpt", action="store_true",
                        help="Skip MoneyPrinterTurbo stage")
    parser.add_argument("--skip-clipper", action="store_true",
                        help="Skip vid-clipper stage")

    args = parser.parse_args()
    config = load_config()

    if args.skip_mpt:
        config["skip_mpt"] = True
    if args.skip_clipper:
        config["skip_clipper"] = True

    if args.run_now:
        task_dir = run_one_video(seed=args.seed, config=config)
        print(f"\n{'='*60}")
        print(f"  Task directory: {task_dir}")
        print(f"  Report: {task_dir / 'REPORT.md'}")
        print(f"{'='*60}")

    elif args.schedule:
        run_scheduler(config)

    else:
        parser.print_help()
