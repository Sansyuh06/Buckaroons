# Main Pipeline
# ---------------------------------------------------------------------------

def run_one_video(seed: Optional[int] = None, config: Optional[dict] = None) -> Path:
    """
    Run the complete video generation pipeline for one video.
    Stages are serialized to respect GPU memory constraints.

    Returns the task directory path.
    """
    if config is None:
        config = load_config()

    if seed is None:
        seed = int(datetime.now().timestamp()) % 100000

    # Create task directory
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    task_dir = OUTPUT_ROOT / "tasks" / f"{timestamp}_seed{seed}"
    task_dir.mkdir(parents=True, exist_ok=True)

    log_dir = OUTPUT_ROOT / "logs"
    setup_logging(log_dir)

    logger.info("=" * 60)
    logger.info(f"VIDEO FACTORY — Starting run (seed={seed})")
    logger.info(f"Task directory: {task_dir}")
    logger.info("=" * 60)

    topic = {}
    script_data = {}
    narration_path = None
    final_video = None
    short_clips = []
    error_msg = None

    try:
        # ── Stage 1: PDF Ingestion ──────────────────────────────────
        logger.info("━━━ STAGE 1: PDF Ingestion ━━━")
        index_path = OUTPUT_ROOT / "library_index.json"
        if not index_path.exists():
            index_path = ingest_pdfs()
        else:
            logger.info("Using existing library index")

        # ── Stage 2a: Topic Selection ───────────────────────────────
        logger.info("━━━ STAGE 2a: Topic Selection ━━━")
        topic = pick_topic(index_path, task_dir, seed=seed)
        logger.info(f"Topic: {topic.get('topic')}")

        # ── Stage 2b: Script Writing ────────────────────────────────
        logger.info("━━━ STAGE 2b: Script Writing ━━━")
        script_data = write_script(topic, index_path, task_dir, seed=seed)
        script_text = script_data.get("script", "")
        logger.info(f"Script: {len(script_text.split())} words, "
                     f"{len(script_data.get('sources', []))} sources")

        # ── Stage 3: TTS Narration ──────────────────────────────────
        logger.info("━━━ STAGE 3: TTS Narration ━━━")
        narration_path = generate_narration(script_text, task_dir)
        logger.info(f"Narration: {narration_path}")

        # ── Stage 4: MPT Video Production ───────────────────────────
        if not config.get("skip_mpt", False):
            logger.info("━━━ STAGE 4: Video Production (MPT) ━━━")
            final_video = produce_video(script_data, narration_path, topic, task_dir)
            logger.info(f"Video: {final_video}")
        else:
            logger.info("━━━ STAGE 4: SKIPPED (skip_mpt=True) ━━━")

        # ── Stage 5: Short Clips ────────────────────────────────────
        if not config.get("skip_clipper", False) and final_video and final_video.exists():
            logger.info("━━━ STAGE 5: Short Clips (vid-clipper) ━━━")
            short_clips = generate_shorts(final_video, task_dir)
            logger.info(f"Shorts: {len(short_clips)} clips")
        else:
            logger.info("━━━ STAGE 5: SKIPPED ━━━")

        # ── Copy to ready/ ──────────────────────────────────────────
        ready_dir = OUTPUT_ROOT / "ready"
        ready_dir.mkdir(parents=True, exist_ok=True)

        if final_video and final_video.exists():
            import shutil
            slug = re.sub(r'[^\w]', '_', topic.get('topic', 'video'))[:50]
            ready_name = f"{timestamp}_{slug}"
            ready_video = ready_dir / f"{ready_name}.mp4"
            shutil.copy2(final_video, ready_video)
            logger.info(f"Ready: {ready_video}")

            for clip in short_clips:
                if clip.exists():
                    shutil.copy2(clip, ready_dir / f"{ready_name}_{clip.name}")

        logger.info("✅ Pipeline completed successfully!")

    except Exception as e:
        error_msg = str(e)
        logger.error(f"❌ Pipeline failed: {e}")
        logger.error(traceback.format_exc())

    # ── Generate Report ─────────────────────────────────────────────
    report = generate_report(
        task_dir, topic, script_data, narration_path,
        final_video, short_clips, error_msg
    )

    # ── Desktop Notification ────────────────────────────────────────
    try:
        import subprocess
        status = "COMPLETE ✅" if not error_msg else f"FAILED ❌"
        topic_name = topic.get("topic", "Unknown")
        subprocess.run([
            "powershell", "-Command",
            f'[Windows.UI.Notifications.ToastNotificationManager, Windows.UI.Notifications, ContentType=WindowsRuntime] | Out-Null; '
            f'$xml = [Windows.UI.Notifications.ToastNotificationManager]::GetTemplateContent([Windows.UI.Notifications.ToastTemplateType]::ToastText02); '
            f'$text = $xml.GetElementsByTagName("text"); '
            f'$text[0].AppendChild($xml.CreateTextNode("Video Factory: {status}")) | Out-Null; '
            f'$text[1].AppendChild($xml.CreateTextNode("{topic_name}")) | Out-Null; '
            f'$toast = [Windows.UI.Notifications.ToastNotification]::new($xml); '
            f'[Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier("Video Factory").Show($toast)'
        ], capture_output=True, timeout=10)
    except Exception:
        pass  # Non-critical

    return task_dir


# ---------------------------------------------------------------------------
# Scheduler
# ---------------------------------------------------------------------------

def run_scheduler(config: dict):
    """Run the pipeline on a schedule using APScheduler."""
    from apscheduler.schedulers.blocking import BlockingScheduler

    interval_days = config.get("schedule_days", 3)
    logger.info(f"Starting scheduler: every {interval_days} days")

    scheduler = BlockingScheduler()
    scheduler.add_job(
        run_one_video,
        "interval",
        days=interval_days,
        kwargs={"config": config},
        id="video_factory",
        name="Video Factory Pipeline",
        next_run_time=datetime.now(),  # Run immediately on start
    )

    try:
        scheduler.start()
    except (KeyboardInterrupt, SystemExit):
        logger.info("Scheduler stopped")


