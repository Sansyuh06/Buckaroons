#!/usr/bin/env python3
"""
pipeline.py — Orchestrator + Scheduler for the local video factory.

Usage:
    python pipeline.py --run-now              # Run one video immediately
    python pipeline.py --run-now --seed=42    # Reproducible run
    python pipeline.py --schedule             # Start scheduler (every 3 days)
"""

import argparse
import json
import logging
import re
import shutil
import sys
import traceback
from datetime import datetime
from pathlib import Path
from typing import Optional

from brain import (
    OUTPUT_ROOT,
    generate_narration,
    generate_shorts,
    ingest_pdfs,
    pick_topic,
    produce_video,
    setup_logging,
    write_script,
)

logger = logging.getLogger("pipeline")

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
CONFIG_PATH = Path(__file__).parent / "pipeline_config.json"

DEFAULT_CONFIG = {
    "schedule_days": 3,
    "auto_publish": False,
    "edge_tts_voice": "en-US-AndrewMultilingualNeural",
    "ollama_model": "qwen3:8b",
    "pexels_api_key": "",
    "skip_mpt": False,       # Skip MPT stage (for testing without Pexels key)
    "skip_clipper": False,   # Skip vid-clipper stage
}


def load_config() -> dict:
    """Load pipeline configuration, creating defaults if needed."""
    if CONFIG_PATH.exists():
        with open(CONFIG_PATH, "r") as f:
            config = json.load(f)
        # Merge with defaults for any missing keys
        for key, val in DEFAULT_CONFIG.items():
            config.setdefault(key, val)
        return config
    else:
        with open(CONFIG_PATH, "w") as f:
            json.dump(DEFAULT_CONFIG, f, indent=2)
        return dict(DEFAULT_CONFIG)


# ---------------------------------------------------------------------------
# Report Generation
# ---------------------------------------------------------------------------

def generate_report(task_dir: Path, topic: dict, script_data: dict,
                    narration_path: Optional[Path],
                    final_video: Optional[Path],
                    short_clips: list[Path],
                    error: Optional[str] = None) -> Path:
    """Generate REPORT.md summarizing the pipeline run."""
    report_path = task_dir / "REPORT.md"
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    status = "✅ COMPLETE" if final_video and final_video.exists() else "❌ FAILED"
    if error:
        status = f"❌ FAILED: {error}"

    sources_md = ""
    for src in script_data.get("sources", []):
        sources_md += f"- **{src.get('pdf', 'N/A')}**, page {src.get('page', '?')}: _{src.get('quote', '')}_\n"

    clips_md = ""
    for clip in short_clips:
        size_mb = clip.stat().st_size / (1024 * 1024) if clip.exists() else 0
        clips_md += f"- `{clip.name}` ({size_mb:.1f} MB)\n"

    report = f"""# Video Factory — Run Report

**Status**: {status}
**Generated**: {timestamp}
**Seed**: {topic.get('seed', 'N/A')}

---

## Topic Selection

| Field | Value |
|-------|-------|
| PDF | {topic.get('pdf_filename', 'N/A')} |
| Topic | {topic.get('topic', 'N/A')} |
| Angle | {topic.get('angle', 'N/A')} |
| Target Duration | {topic.get('target_seconds', 'N/A')}s |

---

## Script

{script_data.get('script', '_No script generated_')}

### Sources (traceable to PDF)
{sources_md if sources_md else '_No sources cited_'}

### Keywords
{', '.join(script_data.get('keywords', []))}

---

## Generated Files

| Asset | Path | Size |
|-------|------|------|
| Narration | `{narration_path.name if narration_path and narration_path.exists() else 'N/A'}` | {f'{narration_path.stat().st_size / (1024*1024):.1f} MB' if narration_path and narration_path.exists() else 'N/A'} |
| Full Video | `{final_video.name if final_video and final_video.exists() else 'N/A'}` | {f'{final_video.stat().st_size / (1024*1024):.1f} MB' if final_video and final_video.exists() else 'N/A'} |

### Short Clips (9:16)
{clips_md if clips_md else '_No clips generated_'}

---

## Upload Checklist

- [ ] Watch the video end-to-end — verify facts match the source PDF
- [ ] Set audience = **Not-for-kids**
- [ ] Set AI-disclosure = **YES**
- [ ] Paste the sources list below into the video description
- [ ] Add hashtags from keywords above

### Description Template

```
{topic.get('topic', 'Quantum Computing')}

Sources:
{chr(10).join(f"• {s.get('pdf', '')} p.{s.get('page', '?')}" for s in script_data.get('sources', []))}

#quantum #science #education #physics #shorts
```

---

> ⚠️ DEFAULT = DO NOT AUTO-PUBLISH. The human verifies before upload.

Generated by Video Factory Pipeline
"""

    with open(report_path, "w", encoding="utf-8") as f:
        f.write(report)

    logger.info(f"Report saved: {report_path}")
    return report_path


